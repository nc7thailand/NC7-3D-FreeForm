import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const wat = path.join(root, 'src/wasm/silhouette_raster.wat')
const wasm = path.join(root, 'src/wasm/silhouette_raster.wasm')
const out = path.join(root, 'src/lib/silhouetteRasterWasmBytes.js')
const wat2wasm = path.join(root, 'node_modules', '.bin', 'wat2wasm')
const wasmOpt = path.join(root, 'node_modules', '.bin', 'wasm-opt')

execFileSync(wat2wasm, [wat, '-o', wasm], { stdio: 'inherit' })
execFileSync(wasmOpt, ['-O3', '--enable-bulk-memory', '--enable-bulk-memory-opt', wasm, '-o', wasm], { stdio: 'inherit' })
const bytes = readFileSync(wasm)
const source = `// Generated by scripts/build-silhouette-wasm.mjs from src/wasm/silhouette_raster.wat.
// Do not edit by hand. Rebuild with npm run build:wasm.
export const SILHOUETTE_RASTER_WASM_BASE64 = ${JSON.stringify(bytes.toString('base64'))}
`
writeFileSync(out, source)
console.log(`silhouette raster wasm ${bytes.length} bytes`)
